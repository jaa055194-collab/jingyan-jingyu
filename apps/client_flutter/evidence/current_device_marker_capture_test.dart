/// Only the transport is substituted: these rows are generated by a separate
/// run of the production host, then parsed by the real DeviceSessionsApi.
class _CaptureConnection extends HostConnection {
  _CaptureConnection(this.rows)
    : super(Uri.parse('http://fixture.invalid'), 'capture-fixture');

  final List<Object?> rows;
  final requests = <(String, String)>[];

  @override
  Future<List<Object?>> requestList(
    String method,
    String path, {
    Map<String, Object?>? body,
    Map<String, String>? query,
    bool retryAuthentication = true,
  }) async {
    requests.add((method, path));
    expect((method, path), ('GET', Routes.authDevices));
    expect(body, isNull);
    expect(query, isNull);
    return rows;
  }

  @override
  Future<Map<String, Object?>> request(
    String method,
    String path, {
    Map<String, Object?>? body,
    Map<String, String>? query,
    bool retryAuthentication = true,
    bool allowEmptySuccess = false,
  }) async {
    requests.add((method, path));
    throw StateError('The capture must not issue a device write');
  }
}

class _CaptureRuntime extends ClientRuntime {
  _CaptureRuntime(HostConnection host) {
    connection = host;
  }

  @override
  bool get ready => true;
  @override
  bool get onboarded => true;
  @override
  bool get chatEntered => true;
  @override
  bool get online => true;
  @override
  String? get connectedAccountId => 'fixture-owner';
  @override
  ThemeMode get themeMode => ThemeMode.light;
}

void main() {
  testWidgets('capture the same peer sign-off from real host rows', (
    tester,
  ) async {
    const rowsPath = String.fromEnvironment('CAPTURE_ROWS');
    const pngPath = String.fromEnvironment('CAPTURE_PATH');
    const marked = bool.fromEnvironment('CAPTURE_EXPECT_CURRENT');
    const font = String.fromEnvironment('CAPTURE_CJK_FONT');
    const icons = String.fromEnvironment('CAPTURE_ICON_FONT');
    expect(rowsPath, isNotEmpty);
    expect(pngPath, isNotEmpty);
    for (final (family, path) in [('Ahem', font), ('MaterialIcons', icons)]) {
      final bytes = File(path).readAsBytesSync();
      await (FontLoader(
        family,
      )..addFont(Future.value(ByteData.sublistView(bytes)))).load();
    }
    tester.view.physicalSize = const Size(1280, 960);
    tester.view.devicePixelRatio = 1;
    tester.platformDispatcher.textScaleFactorTestValue = 1;
    addTearDown(tester.view.resetPhysicalSize);
    addTearDown(tester.view.resetDevicePixelRatio);
    addTearDown(tester.platformDispatcher.clearTextScaleFactorTestValue);

    final rows = (jsonDecode(File(rowsPath).readAsStringSync()) as List)
        .cast<Object?>();
    final connection = _CaptureConnection(rows);
    final runtime = _CaptureRuntime(connection);
    final boundary = GlobalKey();
    try {
      await tester.pumpWidget(
        RepaintBoundary(
          key: boundary,
          child: WhaleChatApp(model: runtime),
        ),
      );
      await tester.tap(find.byTooltip('设置'));
      await tester.pumpAndSettle();
      expect(connection.requests, isEmpty);
      await tester.tap(find.byKey(const Key('open-device-sessions')));
      await tester.pumpAndSettle();
      expect(connection.requests, [('GET', Routes.authDevices)]);

      final local = find.byKey(const Key('device-row-fixture-local'));
      final peer = find.byKey(const Key('device-row-fixture-peer'));
      expect(local, findsOneWidget);
      expect(peer, findsOneWidget);
      expect(
        find.byKey(const Key('device-current-fixture-local')),
        marked ? findsOneWidget : findsNothing,
      );
      expect(
        find.byKey(const Key('device-current-fixture-peer')),
        findsNothing,
      );
      expect(
        find.byKey(const Key('device-current-unknown')),
        marked ? findsNothing : findsOneWidget,
      );
      expect(find.text('本机'), marked ? findsOneWidget : findsNothing);

      final panel = find.byKey(const Key('device-confirm-panel'));
      final typeName = find.byKey(const Key('device-confirm-name'));
      final submit = find.byKey(const Key('device-confirm-submit'));
      Future<void> choose(String id) async {
        await tester.tap(find.byKey(Key('device-revoke-$id')).hitTestable());
        await tester.pumpAndSettle();
        expect(panel, findsOneWidget);
      }

      await choose('fixture-peer');
      expect(find.text('设备：合成手机（fixture-peer）'), findsOneWidget);
      expect(typeName, marked ? findsNothing : findsOneWidget);
      expect(
        tester.widget<FilledButton>(submit).onPressed,
        marked ? isNotNull : isNull,
      );
      final scrollable = find
          .descendant(
            of: find.byType(DeviceSessionsScreen),
            matching: find.byType(Scrollable),
          )
          .first;
      expect(tester.state<ScrollableState>(scrollable).position.pixels, 0);
      for (final visible in [local, peer, panel]) {
        final rect = tester.getRect(visible);
        expect(rect.top, greaterThanOrEqualTo(0));
        expect(rect.bottom, lessThanOrEqualTo(960));
      }
      expect(tester.takeException(), isNull);
      final painter =
          boundary.currentContext!.findRenderObject()! as RenderRepaintBoundary;
      final png = await tester.runAsync(() async {
        final pixels = await painter.toImage();
        try {
          expect((pixels.width, pixels.height), (1280, 960));
          return await pixels.toByteData(format: ui.ImageByteFormat.png);
        } finally {
          pixels.dispose();
        }
      });
      File(pngPath).writeAsBytesSync(
        png!.buffer.asUint8List(png.offsetInBytes, png.lengthInBytes),
      );

      // Check both hosts keep the stronger confirmation for this device.
      await tester.tap(find.byKey(const Key('device-confirm-cancel')));
      await tester.pumpAndSettle();
      await choose('fixture-local');
      expect(find.text('设备：合成笔记本（fixture-local）'), findsOneWidget);
      expect(typeName, findsOneWidget);
      expect(tester.widget<FilledButton>(submit).onPressed, isNull);
      await tester.enterText(typeName, '合成手机');
      await tester.pumpAndSettle();
      expect(tester.widget<FilledButton>(submit).onPressed, isNull);
      await tester.enterText(typeName, '合成笔记本');
      await tester.pumpAndSettle();
      expect(tester.widget<FilledButton>(submit).onPressed, isNotNull);
      expect(connection.requests, [('GET', Routes.authDevices)]);
      expect(tester.takeException(), isNull);
    } finally {
      await tester.pumpWidget(const SizedBox.shrink());
      runtime.dispose();
    }
  });
}
